def c_to_f(c):
    """
   funkcja zamienia stopnie celsjusza na stopnie fahrenheita
    """
    f=c*(9/5)+32
    return f

def predkosc_wiatru(vm):
    """
    funkcja zamienia  metry na sekunde na kilometry na godzine
    """
    vk=vm*3.6
    return vk


def cisnienie_atmosferyczne(hpa):
    """
    funkcja zamienia ciśnienie atmosferyczne z hektopaskali [hPa] na milimetry słupa rtęci
    """
    p=hpa/1.333
    return p







